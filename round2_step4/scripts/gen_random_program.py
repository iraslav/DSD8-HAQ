#!/usr/bin/env python3
"""
gen_random_program.py -- constrained-random DSD-8 test programs
(Architecture & Toolchain Guide, slide 54, widened as it recommends).

Every program:
  * initialises all eight registers with random constants,
  * emits N random instructions drawn from: all ALU ops, CMP, LDI, LD, ST,
    MOV/NOP, IN/OUT on safe ports (switches, LEDs, 7-seg, SLOW_ECHO,
    unmapped), and FORWARD-ONLY conditional branches / JMPs (so every
    program terminates),
  * ends with HLT.
The golden model (tools/dsd8sim.py) supplies the expected trace, so every
program is self-checking. The seed is in the file name: a failing seed is
a permanent regression test.

Usage:
    python3 scripts/gen_random_program.py --seed 7 --count 300 -o tests/extra/R007_random.asm
"""
import argparse
import random

ALU3 = ["ADD", "SUB", "AND", "OR", "XOR"]
BRANCHES = ["BEQ", "BNE", "BCS", "BCC", "BMI", "BPL", "BVS", "BVC"]
IN_PORTS = [0x00, 0x01, 0x40, 0x03, 0x7E]
OUT_PORTS = [0x02, 0x10, 0x11, 0x40, 0x05, 0xC0]


def generate(seed, count):
    rng = random.Random(seed)
    r = lambda: rng.randrange(8)
    lines = [f"; random program, seed {seed}, {count} body instructions",
             "; generated by scripts/gen_random_program.py -- forward-only branches, always halts"]
    for reg in range(8):
        lines.append(f"        LDI  R{reg}, 0x{rng.randrange(256):02X}")
    pending = []          # labels that still need to be placed
    label_id = 0
    for i in range(count):
        # place any label whose distance has elapsed
        for lab in [p for p in pending if p[1] <= i]:
            lines.append(f"{lab[0]}:")
            pending.remove(lab)
        k = rng.random()
        if k < 0.40:
            lines.append(f"        {rng.choice(ALU3)}  R{r()}, R{r()}, R{r()}")
        elif k < 0.48:
            lines.append(f"        {rng.choice(['SHL', 'SHR'])}  R{r()}, R{r()}")
        elif k < 0.56:
            lines.append(f"        CMP  R{r()}, R{r()}")
        elif k < 0.62:
            lines.append(f"        LDI  R{r()}, 0x{rng.choice([0, 1, 0x7F, 0x80, 0xFF, rng.randrange(256)]):02X}")
        elif k < 0.70:
            lines.append(f"        ST   [R{r()}], R{r()}")
        elif k < 0.78:
            lines.append(f"        LD   R{r()}, [R{r()}]")
        elif k < 0.80:
            lines.append(f"        {rng.choice(['MOV  R%d, R%d' % (r(), r()), 'NOP'])}")
        elif k < 0.85:
            lines.append(f"        IN   R{r()}, 0x{rng.choice(IN_PORTS):02X}")
        elif k < 0.90:
            lines.append(f"        OUT  0x{rng.choice(OUT_PORTS):02X}, R{r()}")
        else:
            name = f"F{label_id}"
            label_id += 1
            op = "JMP" if rng.random() < 0.1 else rng.choice(BRANCHES)
            lines.append(f"        {op}  {name}")
            pending.append((name, i + 1 + rng.randrange(1, 6)))
    for lab in pending:
        lines.append(f"{lab[0]}:")
    lines.append("        HLT")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[1])
    ap.add_argument("--seed", type=int, required=True)
    ap.add_argument("--count", type=int, default=300)
    ap.add_argument("-o", "--output", required=True)
    a = ap.parse_args()
    with open(a.output, "w") as f:
        f.write(generate(a.seed, a.count))


if __name__ == "__main__":
    main()
