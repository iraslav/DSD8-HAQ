#!/usr/bin/env python3
"""
gen_debug_session.py -- writes tests/secure/debug_session.inc, the DEBUG-mode
program both processors run when the mode selector is set to DEBUG, and
splices it into enclave_server.asm and enclave_client.asm (between the
markers ';; >>> DEBUG SESSION' and ';; <<< DEBUG SESSION').

The session debugs the processor's own enclave like a debugger would and
records one bit per check in R7 (LEDs = 0xFF when everything passes):
  bit 0  mode selector really is DEBUG: the private key reads back
  bit 1  built-in self-test: all 8 known-answer test cases pass
  bit 2  breakpoint at exponent bit 8 halts; res = m^17 = 8404, bits_left = 8
  bit 3  single-step x3 advances exactly 3 engine cycles
  bit 4  resume runs to completion: result 8404, 305 busy cycles
  bit 5  trace buffer: 18 multiplies, last entry m^(2^16) = 673D
  bit 6  watchpoint on res == 8404 halts at exponent bit 4 (bits_left = 12)
  bit 7  fault injection is caught by the self-test; removing it passes again
Every wait is bounded, so a broken debugger shows a missing bit instead of hanging.
Values: m = 0x4A0B, debug key N = 0xEC4B, E = 0x11, D = 0xA571 (from Python).
"""
import pathlib, re

def session():
    L = []
    lab = [0]
    def new(prefix):
        lab[0] += 1
        return f"DB{prefix}{lab[0]}"
    def wait_bits(port, mask, fail_label):
        """poll IN port until (value & mask) == mask, at most 255 tries (~6900 cycles,
        more than the ~4300 a full self-test takes)"""
        top = new("W"); ok = new("K")
        return ["        LDI  R0, 0", f"{top}:  IN   R1, 0x{port:02X}", f"        LDI  R2, 0x{mask:02X}",
                "        AND  R3, R1, R2", "        CMP  R3, R2", f"        BEQ  {ok}",
                "        NOP", "        NOP",
                "        SUB  R0, R0, R6", f"        BNE  {top}", f"        JMP  {fail_label}", f"{ok}:  NOP"]
    def expect_in(port, value, fail_label):
        return [f"        IN   R1, 0x{port:02X}", f"        LDI  R2, 0x{value:02X}", "        CMP  R1, R2", f"        BNE  {fail_label}"]
    def out(port, value):
        return [f"        LDI  R1, 0x{value:02X}", f"        OUT  0x{port:02X}, R1"]
    def passbit(bit):
        return [f"        LDI  R2, 0x{1 << bit:02X}", "        OR   R7, R7, R2"]
    def encrypt():
        return out(0x50, 0x0B) + out(0x51, 0x4A) + out(0x58, 0x01)

    L += ["; ======================= DEBUG MODE SESSION =======================",
          "; (generated by scripts/gen_debug_session.py -- edit there)",
          "DEBUG:  LDI  R6, 1",
          "        LDI  R7, 0          ; one bit per passed debug check"]
    L += out(0x52, 0x4B) + out(0x53, 0xEC) + out(0x54, 0x11) + out(0x55, 0x00) + out(0x56, 0x71) + out(0x57, 0xA5)
    # bit 0
    L += ["; bit 0: DEBUG mode -> the (debug) private key can be read back"]
    L += expect_in(0x56, 0x71, "DBC1") + expect_in(0x57, 0xA5, "DBC1") + passbit(0)
    # bit 1
    L += ["; bit 1: built-in self-test, 8 known-answer test cases", "DBC1:   NOP"]
    L += out(0x70, 0x08) + wait_bits(0x71, 0x80, "DBC2") + expect_in(0x7D, 0xFF, "DBC2") + passbit(1)
    # bit 2
    L += ["; bit 2: breakpoint when 8 exponent bits are left; inspect res and bits_left", "DBC2:   NOP"]
    L += out(0x73, 8) + out(0x72, 0x01) + encrypt() + wait_bits(0x71, 0x14, "DBC3")
    L += out(0x76, 3) + expect_in(0x77, 0x04, "DBC3") + expect_in(0x78, 0x84, "DBC3")
    L += out(0x76, 1) + expect_in(0x77, 8, "DBC3") + passbit(2)
    # bit 3
    L += ["; bit 3: single-step three times = three engine cycles", "DBC3:   NOP"]
    L += out(0x76, 10) + ["        IN   R4, 0x77       ; cycle counter before"]
    L += out(0x70, 0x04) + ["        OUT  0x70, R1", "        OUT  0x70, R1"]
    L += ["        IN   R1, 0x77", "        LDI  R2, 3", "        ADD  R4, R4, R2", "        CMP  R1, R4", "        BNE  DBC4"] + passbit(3)
    # bit 4
    L += ["; bit 4: remove the breakpoint, resume, check result and cycle count", "DBC4:   NOP"]
    L += out(0x72, 0x00) + out(0x70, 0x02) + wait_bits(0x59, 0x02, "DBC5")
    L += expect_in(0x5A, 0x04, "DBC5") + expect_in(0x5B, 0x84, "DBC5")
    L += out(0x76, 10) + expect_in(0x77, 0x31, "DBC5") + expect_in(0x78, 0x01, "DBC5") + passbit(4)
    # bit 5
    L += ["; bit 5: trace buffer of multiply results", "DBC5:   NOP"]
    L += expect_in(0x7C, 18, "DBC6") + out(0x79, 1) + expect_in(0x7A, 0x3D, "DBC6") + expect_in(0x7B, 0x67, "DBC6") + passbit(5)
    # bit 6
    L += ["; bit 6: watchpoint -- halt when a multiply writes res = 8404", "DBC6:   NOP"]
    L += out(0x74, 0x04) + out(0x75, 0x84) + out(0x72, 0x02) + encrypt() + wait_bits(0x71, 0x24, "DBC7")
    L += out(0x76, 1) + expect_in(0x77, 12, "DBC7")
    L += out(0x72, 0x00) + out(0x70, 0x02) + wait_bits(0x59, 0x02, "DBC7") + passbit(6)
    # bit 7
    L += ["; bit 7: inject a stuck-at fault -> self-test must FAIL; remove it -> PASS", "DBC7:   NOP"]
    L += out(0x72, 0x10) + out(0x70, 0x08) + wait_bits(0x71, 0x80, "DBEND")
    L += ["        IN   R1, 0x7E", "        LDI  R2, 0x00", "        CMP  R1, R2", "        BEQ  DBEND       ; fault not detected"]
    L += out(0x72, 0x00) + out(0x70, 0x08) + wait_bits(0x71, 0x80, "DBEND") + expect_in(0x7D, 0xFF, "DBEND") + passbit(7)
    L += ["; report: LEDs = passed checks (FF = debugger and enclave healthy), 7-seg 'dB'",
          "DBEND:  OUT  0x02, R7", "        LDI  R1, 0xDB", "        OUT  0x10, R1", "        LDI  R1, 0x03",
          "        OUT  0x11, R1", "        HLT"]
    return L

def mode_check():
    return ["; ---- MODE SELECTOR: enclave STATUS bit 4 = 1 -> DEBUG mode ----",
            "        IN   R1, 0x59", "        LDI  R2, 0x10", "        AND  R3, R1, R2", "        BEQ  SECURE",
            "        JMP  DEBUG", "SECURE: NOP          ; ---- secure communication mode ----"]

text = "\n".join(session()) + "\n"
pathlib.Path("tests/secure/debug_session.inc").write_text(text)
for name in ("enclave_server.asm", "enclave_client.asm"):
    p = pathlib.Path("tests/secure") / name
    s = p.read_text()
    s = re.sub(r";; >>> MODE CHECK.*?;; <<< MODE CHECK\n", "", s, flags=re.S)
    s = re.sub(r";; >>> DEBUG SESSION.*?;; <<< DEBUG SESSION\n", "", s, flags=re.S)
    lines = s.splitlines()
    first = next(i for i, l in enumerate(lines) if l.strip() and not l.lstrip().startswith(";"))
    lines[first:first] = [";; >>> MODE CHECK"] + mode_check() + [";; <<< MODE CHECK"]
    s = "\n".join(lines) + "\n"
    s += ";; >>> DEBUG SESSION\n" + text + ";; <<< DEBUG SESSION\n"
    p.write_text(s)
print("debug session spliced into enclave_server.asm and enclave_client.asm")
